# ЗАДАНИЕ 4. Функция для квеста — урон
# Создай функцию apply_damage(health, damage).
# Она должна печатать "Ты получаешь урон <damage>!"
# и возвращать новое здоровье (health - damage).
# Вызови её и напечатай результат.

